// Writes docs/CATALOG-COVERAGE.md from the built catalog's index: counts, retrieval dates, each company's discovery and
// what is known to be missing. Only counts and the registry's own names go into the repository, no TMDB records.
//   node tools/screen-catalog/coverage.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { COMPANIES, DISCOVERED, LEADERSHIP, REGISTRY_CHECKED, REGISTRY_CHECKED_NBCU } from '../../src/catalog/registry.ts';

const ix = JSON.parse(readFileSync('.screen-catalog/index.json', 'utf8'));
const n = (x) => (x ?? 0).toLocaleString('en-US');
const c = ix.counts;
const rows = DISCOVERED.map((co) => {
  const q = (t) => ix.discovery.find((d) => d.company === co.tmdb.id && d.type === t);
  const m = q('movie'), t = q('tv');
  const built = ix.companies.find((x) => x.tmdbId === co.tmdb.id);
  return `| ${co.name} | ${co.tmdb.id} | ${n(m?.reported)} / ${n(m?.found)} (${m?.pages} pages) | ${n(t?.reported)} / ${n(t?.found)} (${t?.pages} pages) | ${n(built?.movies)} | ${n(built?.series)} |`;
});
const gaps = ix.discovery.filter((d) => d.failedPages.length || d.reported === null || d.found < d.reported);
const extra = ix.discovery.filter((d) => d.reported !== null && d.found > d.reported);
const md = `# Screen Catalog Coverage

Generated by \`tools/screen-catalog/coverage.mjs\` from the catalog built ${ix.builtAt.slice(0, 10)}. The rules and sources
are in \`docs/CATALOG.md\`. The catalog itself isn't in the repository.

## Retrieval

- **Source:** TMDB's API (api.themoviedb.org/3), through the cloud session's proxy.
- **Retrieved:** ${ix.retrieved.from} to ${ix.retrieved.to}.
- **Refreshing:** responses older than ${ix.retrieved.maxAgeDays} days are fetched again, under TMDB's terms.
- **Registry:** companies and leadership researched and checked ${REGISTRY_CHECKED} (Disney's) and ${REGISTRY_CHECKED_NBCU} (NBCUniversal's).
- **Failed requests left:** ${ix.failures}. **Stale responses left out:** ${ix.stale}.

## Counts

| What | Count |
| --- | --- |
| Companies in the registry | ${COMPANIES.length} (${DISCOVERED.length} with titles gathered, ${COMPANIES.filter((x) => x.kind === 'network').length} networks and services, ${COMPANIES.filter((x) => x.kind === 'corporate').length} parents) |
| Leadership roles recorded | ${LEADERSHIP.length}, for ${new Set(LEADERSHIP.map((r) => r.personId)).size} people |
| Films | ${n(c.movies)} |
| Series | ${n(c.series)} |
| Seasons | ${n(c.seasons)} |
| Episodes | ${n(c.episodes)} |
| People credited | ${n(c.people)} |
| People with their details gathered | ${n(c.peopleWithDetails)} |
| Film and series cast credits | ${n(c.castCredits)} |
| Film and series crew credits | ${n(c.crewCredits)} |
| Episode credits (crew and guest cast) | ${n(c.episodeCredits)} |
| Titles discovered but not fetched | ${n(c.missingTitles)} |
| Seasons listed but not fetched | ${n(c.missingSeasons)} |

Every title is counted once by media type and TMDB ID, though many are credited to several of these companies.

## Discovery, Company By Company

Each cell gives the titles TMDB reported for the query, then the distinct titles found reading every page. "Kept" is the
titles whose details still credit the company, plus those found through discovery whose credits no longer do.

| Company | TMDB ID | Films reported / found | Series reported / found | Films kept | Series kept |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

${gaps.length ? `Queries with failed pages or fewer titles found than reported: ${gaps.map((d) => `${d.company} ${d.type}`).join(', ')}.` : 'Every query was read to its last page, and none found fewer titles than it reported.'} ${extra.length ? `${extra.map((d) => `Company ${d.company}'s ${d.type === 'movie' ? 'films' : 'series'} found ${d.found - d.reported} more than reported, because TMDB's results changed while its pages were read.`).join(' ')}` : ''} No query reached TMDB's 500-page cap, so none had to be split.

## What This Is, And Isn't

- **What it is:** everything TMDB returned for these ${DISCOVERED.length} companies' discovery queries, with full cast
  and crew for each title, and every season and episode of each series.
- **What it isn't:** every Disney production ever made. TMDB credits are contributed by its users, and some titles
  credit a different record of the same company, or none.
- **Not checked against official catalogs.** No title was checked against the companies' own catalogs or filmographies,
  so none is marked as independently confirmed.
- **Known gaps:**
  - TMDB records not covered: the second Touchstone Television record (141822), the older 20th Television record (21659)
    and Fox Television Studios (6529). The reasons are in \`docs/CATALOG.md\`.
  - Adult titles and video releases: TMDB's discovery leaves these out by default, and the queries kept those defaults.
  - Person details: gathered for ${n(c.peopleWithDetails)} people under the declared rule. ${c.people > c.peopleWithDetails ? `The other
    ${n(c.people - c.peopleWithDetails)} have credits only.` : 'No one credited is without them.'}
  - Leadership: none is listed for 20th Century Studios, Searchlight Pictures or Walt Disney Pictures, nor for Universal
    Pictures, Focus Features, DreamWorks Animation or Working Title (\`docs/CATALOG.md\`).
- **Rights exclusions:** no posters, stills or photographs are shown, because their rights belong to their holders. No
  TMDB data is committed or put in builds.
`;
writeFileSync('docs/CATALOG-COVERAGE.md', md);
console.log('docs/CATALOG-COVERAGE.md written.');
